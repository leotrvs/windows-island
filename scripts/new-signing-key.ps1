# Creates the update signing key. Run once per project (forks need their own key).
# The private key is written outside the repository; only the public key goes into src\UpdateKey.cs.
param([string]$KeyPath = (Join-Path $HOME '.windows-island-signing\update-signing-key.xml'))

$ErrorActionPreference = 'Stop'
if (Test-Path $KeyPath) { throw "A key already exists at $KeyPath. Replacing it would break updates for installed copies." }

$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
if ([IO.Path]::GetFullPath($KeyPath).StartsWith($repo, [StringComparison]::OrdinalIgnoreCase)) {
    throw 'The private key must stay outside the repository.'
}

$rsa = [System.Security.Cryptography.RSA]::Create(3072)
New-Item -ItemType Directory -Force -Path (Split-Path $KeyPath) | Out-Null
[IO.File]::WriteAllText($KeyPath, $rsa.ToXmlString($true))

$public = $rsa.ToXmlString($false)
$source = @"
// Generated by scripts/new-signing-key.ps1. This is the public half only, so it is safe to commit.
// While empty, automatic updates are disabled.
namespace WindowsIsland
{
    static class UpdateKey
    {
        public const string PublicKeyXml = "$public";
    }
}

"@
[IO.File]::WriteAllText((Join-Path $repo 'src\UpdateKey.cs'), $source.Replace("`r`n", "`n"), (New-Object Text.UTF8Encoding $false))
"Private key: $KeyPath"
'Back it up somewhere safe, such as a password manager. Without it, installed copies can no longer be updated.'
